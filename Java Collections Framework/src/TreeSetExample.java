import java.util.TreeSet;

public class TreeSetExample {
    //TreeSet Interface
    public static void main(String[] args){
        TreeSet<Integer> set=new TreeSet<>();
        set.add(50);
        set.add(90);
        set.add(85);
        set.add(10);
        set.add(35);
        set.add(20);
        set.add(15);
        System.out.println(set);
    }
}
